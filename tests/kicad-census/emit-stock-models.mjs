// Writes `src/model/kicad/board/stockModels.ts`: the STEP models of KiCad's 3D library at one release,
// so the board importer can tell a model the parts index serves (`GET /api/v1/parts/models/kicad/<release>/<path>`
// streams the file from KiCad's repository at that tag) from a name that no longer exists there.
//
//   git clone --no-checkout --filter=blob:none --depth 1 --branch 10.0.7 https://gitlab.com/kicad/libraries/kicad-packages3D.git repo
//   git -C repo ls-tree -r --name-only <the commit the tag points at> > list.txt
//   node tests/kicad-census/emit-stock-models.mjs 10.0.7 list.txt

import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const OUT = join(here, "..", "..", "src", "model", "kicad", "board", "stockModels.ts")

const [, , release, listFile] = process.argv
if (!release || !listFile) {
  console.error("usage: node emit-stock-models.mjs <release> <git ls-tree list>")
  process.exit(1)
}
const byLibrary = new Map()
for (const line of readFileSync(listFile, "utf8").split(/\r?\n/)) {
  const m = /^([^/]+\.3dshapes)\/([^/]+)\.step$/.exec(line)
  if (!m) continue
  const names = byLibrary.get(m[1]) ?? []
  names.push(m[2])
  byLibrary.set(m[1], names)
}
const libraries = [...byLibrary].sort(([a], [b]) => (a < b ? -1 : 1)).map(([lib, names]) => `  ${JSON.stringify(lib)}: ${JSON.stringify(names.sort().join("|"))},`)
const count = [...byLibrary.values()].reduce((n, names) => n + names.length, 0)

writeFileSync(
  OUT,
  `// GENERATED by tests/kicad-census/emit-stock-models.mjs. Do not edit.
// The ${count} STEP models of KiCad's 3D library at release ${release} (${byLibrary.size} libraries), by library
// directory: the models the editor's parts index can serve for a \`kicad\` model id (\`${release}/<library>.3dshapes/<name>.step\`).

export const STOCK_MODEL_RELEASE = ${JSON.stringify(release)}

const LIBRARIES: Record<string, string> = {
${libraries.join("\n")}
}

const parsed = new Map<string, ReadonlySet<string>>()

/** Whether KiCad's 3D library has \`<library>/<name>.step\` at the release above. */
export function stockModelExists(library: string, name: string): boolean {
  let names = parsed.get(library)
  if (!names) {
    const joined = Object.hasOwn(LIBRARIES, library) ? LIBRARIES[library] : ""
    names = new Set(joined ? joined.split("|") : [])
    parsed.set(library, names)
  }
  return names.has(name)
}
`,
)
console.log(`wrote ${OUT}: ${count} models in ${byLibrary.size} libraries`)
