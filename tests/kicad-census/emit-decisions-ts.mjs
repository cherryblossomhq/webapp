// Writes `src/model/kicad/board/decisions.ts` from `decisions.mjs`: the reader's own copy of the
// decision table, so that what the census was judged against is what the importer runs on.
// `tests/kicad-board-decisions.test.ts` fails when the copy and the table drift apart.
//
//   node tests/kicad-census/emit-decisions-ts.mjs

import { writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { ATOMS, RULES, TOKENS } from "./decisions.mjs"

const here = dirname(fileURLToPath(import.meta.url))
export const OUT = join(here, "..", "..", "src", "model", "kicad", "board", "decisions.ts")

export function render() {
  const rules = RULES.map((r) => ({ source: r.path.source, decision: r.decision, ...(r.ext ? { ext: r.ext } : {}), ...(r.note ? { note: r.note } : {}) }))
  const atoms = ATOMS.map((a) => ({ source: a.path.source, values: [...a.values], skip: a.skip, ...(a.free ? { free: true } : {}) }))
  const tokens = TOKENS.map((t) => ({ names: t.names, decision: t.decision, ...(t.ext ? { ext: t.ext } : {}), note: t.note }))
  return `// GENERATED by tests/kicad-census/emit-decisions-ts.mjs from tests/kicad-census/decisions.mjs. Do not edit.
// What the importer does with every node path, value atom and keyword of a KiCad board.

export type Decision = "native" | "extend" | "not-needed" | "report"

export interface PathRule {
  /** A regular expression over the whole path from the root, \`zone>polygon>pts\`; \`module\` is read as \`footprint\`. */
  source: string
  decision: Decision
  /** The extension of the model the node needs (X1 to X24 in docs/kicad-import.md), for \`extend\`. */
  ext?: string
  note?: string
}

export interface AtomRule {
  source: string
  values: string[]
  /** Positions of the list that hold a name or number the file's author chose. */
  skip: number[]
  /** Every bare word of the list is a name, an identity or text the file's author chose. */
  free?: boolean
}

export interface TokenRule {
  names: string[]
  decision: Decision
  ext?: string
  note: string
}

export const PATH_RULES: PathRule[] = ${JSON.stringify(rules, null, 1)}

export const ATOM_RULES: AtomRule[] = ${JSON.stringify(atoms, null, 1)}

export const TOKEN_RULES: TokenRule[] = ${JSON.stringify(tokens, null, 1)}
`
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT, render())
  console.log(`wrote ${OUT}`)
}
