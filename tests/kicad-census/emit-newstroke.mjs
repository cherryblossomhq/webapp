// Writes KiCad's stroke font into the two modules `src/lib/kicadFont/glyphsBase.ts` (U+0020 to U+2FFF) and `glyphsCjk.ts`
// (U+3000 to U+FFEE) from a copy of KiCad's `common/newstroke_font.cpp`:
//
//   node tests/kicad-census/emit-newstroke.mjs <path to newstroke_font.cpp>
//
// The data is KiCad's and keeps KiCad's licence header (GPL-2.0-or-later, with the MIT notice of the CJK code and the SIL Open
// Font License 1.1 of Source Han Sans). Each glyph is KiCad's own string, unchanged: `<left><right>` then pairs of letters,
// ` R` lifting the pen, every letter the code of `R` plus a number. One glyph per line; the glyph of code point `c` is line
// `c - 0x20` of the whole font, which is the table's own order (the comments of the source name each block's first code).

import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { dirname, join } from "node:path"

const input = process.argv[2]
if (!input) throw new Error("usage: node emit-newstroke.mjs <newstroke_font.cpp>")
const src = readFileSync(input, "utf8").replace(/\r\n/g, "\n")
const lines = src.split("\n")
const headerEnd = lines.findIndex((l) => l.startsWith("#include"))
const header = lines.slice(0, headerEnd).join("\n").trimEnd()
const start = src.indexOf("newstroke_font[] =")
const glyphs = []
for (const m of src.slice(start).matchAll(/^\s*"((?:[^"\\]|\\.)*)",?\s*(?:\/\*.*\*\/)?\s*$/gm)) glyphs.push(m[1].replace(/\\(.)/g, "$1"))

const CJK_FROM = 0x3000
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "src", "lib", "kicadFont")
const note = (what) => `${header}\n\n/*\n * This file holds ${what} of KiCad's stroke font (common/newstroke_font.cpp), as KiCad's own strings, one glyph per line.\n * It is generated by tests/kicad-census/emit-newstroke.mjs and is loaded only when a project has KiCad text.\n */\n\n`
const base = glyphs.slice(0, CJK_FROM - 0x20)
const cjk = glyphs.slice(CJK_FROM - 0x20)
writeFileSync(join(out, "glyphsBase.ts"), `${note(`the glyphs of U+0020 to U+${(CJK_FROM - 1).toString(16).toUpperCase()}`)}/** The glyph of code point 0x20 + i is line i. */\nexport default ${JSON.stringify(base.join("\n"))}\n`)
writeFileSync(join(out, "glyphsCjk.ts"), `${note(`the glyphs of U+${CJK_FROM.toString(16).toUpperCase()} to U+${(0x1f + glyphs.length).toString(16).toUpperCase()}`)}/** The glyph of code point 0x3000 + i is line i. */\nexport default ${JSON.stringify(cjk.join("\n"))}\n`)
console.log("glyphs", glyphs.length, "base", base.length, "cjk", cjk.length)
